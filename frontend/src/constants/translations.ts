/** Fill {placeholders} in a translation string. */
export const fmt = (template: string, vars: Record<string, string | number>) =>
  template.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`));

/** Translate backend month codes ('Jun') for display. */
export const translateMonths = (months: string[] = [], t) =>
  months.map(m => t.months?.[m] || m).join(', ');
